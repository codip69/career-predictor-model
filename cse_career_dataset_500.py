"""Train a career-path classifier on cse_career_dataset_500.csv

Usage:  pip install pandas scikit-learn joblib
        python train_career_model.py
"""
import joblib
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report
from sklearn.model_selection import StratifiedKFold, cross_val_score, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder

CSV = "cse_career_dataset_500.csv"
TARGET = "target_career_path"

# Single-choice columns -> one-hot
SINGLE = ["semester", "domain", "career_goal", "focus",
          "time_commitment", "english_proficiency"]
# Comma-separated multi-choice columns -> one 0/1 column per item
MULTI = ["languages", "core_subjects", "tools_and_docs"]

df = pd.read_csv(CSV)
X, y = df.drop(columns=[TARGET]), df[TARGET]

def split_commas(s):
    return s.split(",")


# Tokenizer splits on commas only, so "C# (.NET)" and "Git / GitHub" stay intact
transformers = [("single", OneHotEncoder(handle_unknown="ignore"), SINGLE)]
for col in MULTI:
    transformers.append((col, CountVectorizer(tokenizer=split_commas,
                                              token_pattern=None, lowercase=False,
                                              binary=True), col))
prep = ColumnTransformer(transformers)

models = {
    "logistic_regression": LogisticRegression(max_iter=3000),
    "random_forest": RandomForestClassifier(n_estimators=300, random_state=42),
}

# 1) Compare models with 5-fold cross-validation (more reliable than one split on 500 rows)
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
scores = {}
for name, model in models.items():
    pipe = Pipeline([("prep", prep), ("model", model)])
    scores[name] = cross_val_score(pipe, X, y, cv=cv).mean()
    print(f"{name}: CV accuracy = {scores[name]:.3f}")

# 2) Train best model on a train split, evaluate on held-out test set
best = max(scores, key=scores.get)
X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.2,
                                          stratify=y, random_state=42)
final = Pipeline([("prep", prep), ("model", models[best])]).fit(X_tr, y_tr)
pred = final.predict(X_te)
print(f"\nBest: {best} | test accuracy = {accuracy_score(y_te, pred):.3f}")
print(classification_report(y_te, pred, zero_division=0))

# 3) Save the model trained on ALL data, and show a sample prediction
final.fit(X, y)
joblib.dump(final, "career_model.joblib")

sample = pd.DataFrame([{
    "semester": "3rd Year (Advanced topics)",
    "languages": "Python,JavaScript",
    "core_subjects": "DBMS,OOP",
    "tools_and_docs": "Git / GitHub,Docker / AWS",
    "domain": "Machine Learning, AI & Data Science",
    "career_goal": "Remote Tech Job (Global / International Market)",
    "focus": "Building Real-world Production-grade Projects",
    "time_commitment": "3-5 hours/day (Consistent)",
    "english_proficiency": "Intermediate (Conversational)",
}])
proba = final.predict_proba(sample)[0]
top3 = sorted(zip(final.classes_, proba), key=lambda t: -t[1])[:3]
print("\nTop 3 predictions for sample student:")
for label, p in top3:
    print(f"  {label}: {p:.2f}")

